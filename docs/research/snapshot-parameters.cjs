// Snapshot the pinned native schemas. This is documentation tooling, not a UI or validator.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const dbc = require('@meteora-ag/dynamic-bonding-curve-sdk');
const damm = require('@meteora-ag/cp-amm-sdk');
const pinned = [
  { id: 'dbc', package: '@meteora-ag/dynamic-bonding-curve-sdk', idl: dbc.DynamicBondingCurveIdl,
    roots: ['ConfigParameters', 'InitializePoolParameters'],
    instructions: /^(create_config|create_config_with_transfer_hook|initialize_virtual_pool_.*|migration_damm_v2)$/ },
  { id: 'damm-v2', package: '@meteora-ag/cp-amm-sdk', idl: damm.CpAmmIdl,
    roots: ['InitializeCustomizablePoolParameters', 'InitializePoolParameters', 'StaticConfigParameters',
      'BorshFeeTimeScheduler', 'BorshFeeMarketCapScheduler'],
    instructions: /^(initialize_customizable_pool|initialize_pool|initialize_pool_with_dynamic_config|lock_position|permanent_lock_position|initialize_reward|fund_reward|add_liquidity|remove_liquidity)$/ },
];
function definedNames(value, out = new Set()) {
  if (!value || typeof value !== 'object') return out;
  if (value.defined) out.add(value.defined.name);
  for (const nested of Object.values(value)) definedNames(nested, out);
  return out;
}
function typeLabel(value) {
  if (typeof value === 'string') return value;
  if (value.option) return `optional ${typeLabel(value.option)}`;
  if (value.vec) return `list ${typeLabel(value.vec)}`;
  if (value.array) return `${typeLabel(value.array[0])}[${value.array[1]}]`;
  if (value.defined) return value.defined.name;
  return JSON.stringify(value);
}
const snapshots = [];
for (const item of pinned) {
  const allTypes = new Map(item.idl.types.map(t => [t.name, t]));
  const selectedInstructions = item.idl.instructions.filter(ix => item.instructions.test(ix.name));
  const needed = new Set(item.roots);
  for (const ix of selectedInstructions) for (const name of definedNames(ix.args)) needed.add(name);
  const queue = [...needed];
  while (queue.length) {
    const name = queue.shift();
    const type = allTypes.get(name);
    if (!type) throw new Error(`Missing IDL type ${item.id}:${name}`);
    for (const dependency of definedNames(type.type)) if (!needed.has(dependency)) {
      needed.add(dependency); queue.push(dependency);
    }
  }
  const pkg = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../../node_modules', item.package, 'package.json')));
  const types = [...needed].sort().map(name => allTypes.get(name));
  snapshots.push({ protocol: item.id, sdkPackage: item.package, sdkVersion: pkg.version,
    program: item.idl.metadata, programAddress: item.idl.address,
    idlSha256: crypto.createHash('sha256').update(JSON.stringify(item.idl)).digest('hex'),
    roots: item.roots, types, instructions: selectedInstructions });
}
const snapshot = { schemaVersion: 1,
  scope: 'Pinned SDK native argument schemas; not an assertion that every field is user-editable, supported in the app, or mutable after launch.',
  snapshots };
fs.writeFileSync(path.join(__dirname, 'native-parameter-schema.json'), JSON.stringify(snapshot, null, 2) + '\n');
let md = '# Native field inventory from pinned SDKs\n\nGenerated by `node docs/research/snapshot-parameters.cjs`. This inventories arguments and types; it does not count independent controls or implemented features. Editing and simulation rules are in the [Research Studio specification](../RESEARCH_STUDIO.md). Padding is hidden from tables and retained in the JSON snapshot.\n';
for (const item of snapshots) {
  md += `\n## ${item.protocol} — ${item.sdkPackage}@${item.sdkVersion}\n\nProgram IDL ${item.program.version}. The [complete snapshot](native-parameter-schema.json) records the IDL hash, nested types and related instruction arguments/accounts.\n`;
  for (const type of item.types) {
    if (!type.type.fields) continue;
    md += `\n### ${type.name}\n\n| Native field | Type |\n|---|---|\n`;
    for (const field of type.type.fields) {
      if (/padding/i.test(field.name)) continue;
      md += `| \`${field.name}\` | \`${typeLabel(field.type)}\` |\n`;
    }
  }
}
fs.writeFileSync(path.join(__dirname, 'NATIVE_PARAMETERS.md'), md);
console.log('Wrote native schema snapshot and field inventory for pinned DBC/DAMM SDKs.');
